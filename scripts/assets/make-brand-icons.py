"""Draw the brand mark: a 4x4 grid of glowing LEDs whose colour temperature
sweeps from candle (top-left) to sky (bottom-right).

The palette is read from the --brand-* tokens in src/themes/tokens.css, so the
logo cannot drift from the CSS. Writes public/icon.svg, the PWA PNGs
(icon-192/512 and their maskable variants) and the macOS app icon
(desktop/assets/app.icns). Re-run after changing the palette,
then refresh the desktop icons from the new icon-512.png:

    python scripts/assets/make-brand-icons.py
    python scripts/assets/make-desktop-icons.py

Requires Pillow and numpy.
"""
from __future__ import annotations

import re
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "src" / "themes" / "tokens.css"
PUBLIC = ROOT / "public"
MACOS_ICON = ROOT / "desktop" / "assets" / "app.icns"

# Candle to sky, in the order the grid's diagonals use them.
BRAND_TOKENS = [
    "brand-candle",
    "brand-warm-white",
    "brand-soft-white",
    "brand-neutral",
    "brand-daylight",
    "brand-cool-white",
    "brand-sky",
]

# Geometry on the 512 design grid.
SIZE = 512
CORNER_RADIUS = 96
CENTRES = (112, 208, 304, 400)
GLOW_RADIUS = 44
CORE_RADIUS = 16
CORE_OPACITY = 0.95
# Radial glow: (offset along the radius, opacity), linear between stops.
GLOW_STOPS = ((0.0, 1.0), (0.6, 0.6), (1.0, 0.0))
# A maskable icon is cropped to the central 80 % circle, so its grid shrinks
# until the corner glows sit inside that safe zone.
MASKABLE_SCALE = 0.76
SUPERSAMPLE = 4
# macOS app icons sit on a 1024 canvas with the artwork in the central 824
# square, so the Dock and Finder show them at the same size as Apple's own.
MACOS_CANVAS = 1024
MACOS_ARTWORK = 824


def read_hex(css: str, name: str) -> str:
    match = re.search(rf"--{name}:\s*(#[0-9a-fA-F]{{6}})\b", css)
    if not match:
        raise SystemExit(f"--{name} not found in {TOKENS}")
    return match.group(1).lower()


def rgb(hex_colour: str) -> np.ndarray:
    return np.array([int(hex_colour[i:i + 2], 16) for i in (1, 3, 5)], dtype=np.float64) / 255


def grid():
    """Yield (cx, cy, palette index) for each LED, row by row."""
    for row, cy in enumerate(CENTRES):
        for col, cx in enumerate(CENTRES):
            yield cx, cy, row + col


def glow_alpha(distance: np.ndarray) -> np.ndarray:
    t = distance / GLOW_RADIUS
    offsets, opacities = zip(*GLOW_STOPS)
    return np.interp(t, offsets, opacities, right=0.0)


def render(size: int, palette: list[np.ndarray], background: np.ndarray, maskable: bool) -> Image.Image:
    px = size * SUPERSAMPLE
    unit = px / SIZE
    ys, xs = np.mgrid[0:px, 0:px].astype(np.float64)
    # Pixel centres in 512-unit design space.
    x = (xs + 0.5) / unit
    y = (ys + 0.5) / unit
    scale = MASKABLE_SCALE if maskable else 1.0
    # Map design space back through the grid's scale about the centre.
    gx = (x - SIZE / 2) / scale + SIZE / 2
    gy = (y - SIZE / 2) / scale + SIZE / 2

    colour = np.broadcast_to(background, (px, px, 3)).copy()
    leds = list(grid())
    for cx, cy, index in leds:
        d = np.hypot(gx - cx, gy - cy)
        a = glow_alpha(d)[..., None]
        colour = colour * (1 - a) + palette[index] * a
    for cx, cy, index in leds:
        d = np.hypot(gx - cx, gy - cy)
        a = (d <= CORE_RADIUS)[..., None] * CORE_OPACITY
        colour = colour * (1 - a) + palette[index] * a

    if maskable:
        alpha = np.ones((px, px))
    else:
        # Rounded square, same as the SVG's rect rx.
        r = CORNER_RADIUS
        qx = np.clip(np.abs(x - SIZE / 2) - (SIZE / 2 - r), 0, None)
        qy = np.clip(np.abs(y - SIZE / 2) - (SIZE / 2 - r), 0, None)
        alpha = (np.hypot(qx, qy) <= r).astype(np.float64)

    rgba = np.dstack([colour, alpha])
    image = Image.fromarray(np.round(rgba * 255).astype(np.uint8), "RGBA")
    return image.resize((size, size), Image.LANCZOS)


def svg(hexes: list[str], background: str) -> str:
    stops = "".join(
        f'\n      <stop offset="{offset:g}" stop-color="{{c}}" stop-opacity="{opacity:g}"/>'
        for offset, opacity in GLOW_STOPS
    )
    gradients = "".join(
        f'\n    <radialGradient id="k{i}">{stops.format(c=c)}\n    </radialGradient>'
        for i, c in enumerate(hexes)
    )
    glows = "".join(
        f'\n  <circle cx="{cx}" cy="{cy}" r="{GLOW_RADIUS}" fill="url(#k{i})"/>' for cx, cy, i in grid()
    )
    cores = "".join(
        f'\n  <circle cx="{cx}" cy="{cy}" r="{CORE_RADIUS}" fill="{hexes[i]}" opacity="{CORE_OPACITY}"/>'
        for cx, cy, i in grid()
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}">\n'
        "  <!-- Generated by scripts/assets/make-brand-icons.py from the --brand-*\n"
        "       tokens in src/themes/tokens.css. Edit those, not this file. -->\n"
        f'  <rect width="{SIZE}" height="{SIZE}" rx="{CORNER_RADIUS}" fill="{background}"/>\n'
        f"  <defs>{gradients}\n  </defs>{glows}{cores}\n</svg>\n"
    )


def macos_icon(palette: list[np.ndarray], background: np.ndarray) -> Image.Image:
    canvas = Image.new("RGBA", (MACOS_CANVAS, MACOS_CANVAS), (0, 0, 0, 0))
    margin = (MACOS_CANVAS - MACOS_ARTWORK) // 2
    canvas.alpha_composite(render(MACOS_ARTWORK, palette, background, maskable=False), (margin, margin))
    return canvas


def main() -> None:
    css = TOKENS.read_text(encoding="utf-8")
    hexes = [read_hex(css, name) for name in BRAND_TOKENS]
    background = read_hex(css, "bg-primary")
    palette = [rgb(h) for h in hexes]
    bg = rgb(background)

    (PUBLIC / "icon.svg").write_text(svg(hexes, background), encoding="utf-8", newline="\n")
    for size in (192, 512):
        render(size, palette, bg, maskable=False).save(PUBLIC / f"icon-{size}.png", optimize=True)
        render(size, palette, bg, maskable=True).save(PUBLIC / f"icon-maskable-{size}.png", optimize=True)
    # Pillow scales the 1024 artwork to every size an .icns carries.
    macos_icon(palette, bg).save(MACOS_ICON)
    print(f"Wrote {PUBLIC / 'icon.svg'}, 4 PNG icons and {MACOS_ICON}")


if __name__ == "__main__":
    main()
