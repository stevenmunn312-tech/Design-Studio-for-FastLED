/**
 * Rate every bundled audio-reactive pattern and write the ones the Studio
 * Score calls Exceptional (90 or more) to
 * src/state/patterns/bundledExceptionalAudio.ts, the checked-in list the
 * Music Player and Performance Generator starters fill their Pattern
 * Collection from.
 *
 * Studio Scores are computed per machine and matrix size and are never
 * shipped, so a starter cannot ask "which patterns are Exceptional" at run
 * time without rating the whole shelf first. This takes the answer once, at a
 * 16x16 matrix, and commits it.
 *
 * Run: npm run gen:exceptional-audio
 *      (node scripts/run-ts.mjs scripts/assets/exceptional-audio-patterns.ts)
 * Add --scores to print every pattern's score without writing the module.
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { AUDIO_BUNDLED_PATTERNS } from '../../src/state/patterns/bundledPatterns'
import { ratePattern } from '../../src/state/patterns/patternRating'

const GRID = 16
const EXCEPTIONAL = 90

/**
 * In by the author's own judgement whatever they score, and listed first so a
 * starter that takes only the top of the list always has them.
 */
const ALWAYS_INCLUDED = ['Cinder Storm']

const OUTPUT = 'src/state/patterns/bundledExceptionalAudio.ts'

async function main() {
  const scoresOnly = process.argv.includes('--scores')
  // The rater logs each pattern it starts; the table below is the report.
  console.debug = () => undefined
  const rated: { name: string; score: number }[] = []
  for (const pattern of AUDIO_BUNDLED_PATTERNS) {
    const rating = await ratePattern(pattern, { gridW: GRID, gridH: GRID, groups: {}, confirmTrust: async () => false })
    if (rating.failed || rating.skipped) throw new Error(`"${pattern.name}" could not be rated: ${rating.error ?? rating.summary}`)
    rated.push({ name: pattern.name, score: rating.overall })
  }
  for (const name of ALWAYS_INCLUDED) {
    if (!rated.some((entry) => entry.name === name)) throw new Error(`"${name}" is not a bundled audio-reactive pattern`)
  }
  rated.sort((a, b) => b.score - a.score || a.name.localeCompare(b.name))

  if (scoresOnly) {
    for (const entry of rated) console.log(`${String(entry.score).padStart(3)}  ${entry.name}`)
    return
  }

  const pinned = rated.filter((entry) => ALWAYS_INCLUDED.includes(entry.name))
  const scored = rated.filter((entry) => entry.score >= EXCEPTIONAL && !ALWAYS_INCLUDED.includes(entry.name))
  const line = (entry: { name: string; score: number }, note = '') =>
    `  ${JSON.stringify(entry.name).replace(/"/g, '\'')}, // ${entry.score}${note}`
  const source = `// GENERATED by scripts/assets/exceptional-audio-patterns.ts. Do not edit by hand.
// Regenerate with: npm run gen:exceptional-audio
//
// The bundled audio-reactive patterns whose Studio Score is Exceptional
// (${EXCEPTIONAL} or more) on a ${GRID}x${GRID} matrix, best first; each line carries its score.
// Scores are computed per machine and matrix size and are not shipped, so
// this list is the checked-in answer the show starters fill their Pattern
// Collection from. The patterns marked "chosen" are in by the author's own
// judgement whatever they score, and lead the list.

/** Names of bundled audio-reactive patterns, chosen ones first, then by score. */
export const BUNDLED_EXCEPTIONAL_AUDIO_NAMES: readonly string[] = [
${[...pinned.map((entry) => line(entry, ', chosen')), ...scored.map((entry) => line(entry))].join('\n')}
]
`
  writeFileSync(resolve(OUTPUT), source)
  console.log(`${OUTPUT}: ${pinned.length + scored.length} of ${rated.length} bundled audio-reactive patterns`)
}

main().then(() => process.exit(0), (error) => { console.error(error); process.exit(1) })
