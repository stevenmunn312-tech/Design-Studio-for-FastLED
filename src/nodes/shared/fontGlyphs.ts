// Glyph tables for the bitmap fonts with lower case, drawn for this project.
//
// FastLED 3.10.9 ships console fonts of these sizes (src/fl/font), taken from
// the raster-fonts collection by way of WLED. That collection carries no
// licence and credits its bitmaps to other vendors, so nothing here is copied
// from it: every glyph below was drawn by hand on the conventional 5x7 and
// 4x5 grids.
//
// A glyph is written as its rows, top to bottom, '#' lit and '.' dark, joined
// by '|', so a shape can be read and edited where it is stored. `glyphRows`
// turns each into the row numbers `BitmapFont` holds: the leftmost column is
// the highest bit, as in the 3x5 table in font.ts.

/** Row numbers of every glyph in `art`, checked against the cell it is drawn in. */
export function glyphRows(art: Record<string, string>, w: number, h: number): Record<string, number[]> {
  const glyphs: Record<string, number[]> = {}
  for (const [ch, drawn] of Object.entries(art)) {
    const rows = drawn.split('|')
    if (rows.length !== h || rows.some((row) => row.length !== w || /[^#.]/.test(row))) {
      throw new Error(`Glyph ${JSON.stringify(ch)} is not ${w}x${h}`)
    }
    glyphs[ch] = rows.map((row) => [...row].reduce((bits, px) => (bits << 1) | (px === '#' ? 1 : 0), 0))
  }
  return glyphs
}

/**
 * A bold cut of a table: every lit pixel gains a neighbour on its right, so
 * the cell is one column wider and each stroke two pixels thick.
 */
export function boldGlyphs(glyphs: Record<string, number[]>): Record<string, number[]> {
  return Object.fromEntries(Object.entries(glyphs).map(([ch, rows]) => [ch, rows.map((row) => (row << 1) | row)]))
}

