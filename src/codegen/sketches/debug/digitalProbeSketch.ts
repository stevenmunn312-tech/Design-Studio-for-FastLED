/**
 * Debug probe: digital inputs (buttons, switches, sensor outputs, an IR
 * receiver). For each pin it reports the current level, the clean changes
 * seen since the sketch started, and how many of them came within 5 ms of
 * the one before (contact bounce or a noisy line), four times a second, as
 * one `FLS_DBG` line with the pin number in each key: `level_12=1 edges_12=4`.
 */

export const DIGITAL_PROBE_KIND = 'digital'

export interface DigitalProbePin {
  pin: number
  pullup: boolean
}

export function generateDigitalProbeSketch(pins: readonly DigitalProbePin[]): string {
  const safe = pins
    .map((entry) => ({ pin: Math.max(0, Math.min(255, Math.trunc(entry.pin))), pullup: entry.pullup }))
    .filter((entry, index, all) => all.findIndex((other) => other.pin === entry.pin) === index)
    .slice(0, 16)
  const list = safe.map((entry) => entry.pin).join(', ')
  return `// Debug: digital probe — generated by Design Studio for FastLED.
//
// A temporary measuring sketch, not your project. It watches pin${safe.length === 1 ? '' : 's'} ${list}
// and prints a line at 115200 four times a second. Upload the project again
// when you are done.

static const uint8_t PROBE_PINS[] = { ${list} };
static const bool PROBE_PULLUP[] = { ${safe.map((entry) => (entry.pullup ? 'true' : 'false')).join(', ')} };
static const uint8_t PROBE_COUNT = ${safe.length};
static uint8_t probeLevel[PROBE_COUNT];
static uint32_t probeEdges[PROBE_COUNT];
static uint32_t probeBounces[PROBE_COUNT];
static uint32_t probeChanged[PROBE_COUNT];
static uint32_t probePrinted = 0;

void setup() {
  Serial.begin(115200);
  delay(200);
  for (uint8_t i = 0; i < PROBE_COUNT; i++) {
    pinMode(PROBE_PINS[i], PROBE_PULLUP[i] ? INPUT_PULLUP : INPUT);
    probeLevel[i] = digitalRead(PROBE_PINS[i]);
  }
  Serial.println(F("FLS_DBG v=1 probe=${DIGITAL_PROBE_KIND} state=ready"));
}

void loop() {
  const uint32_t now = millis();
  for (uint8_t i = 0; i < PROBE_COUNT; i++) {
    const uint8_t level = digitalRead(PROBE_PINS[i]);
    if (level != probeLevel[i]) {
      if (now - probeChanged[i] < 5) probeBounces[i]++;
      else probeEdges[i]++;
      probeChanged[i] = now;
      probeLevel[i] = level;
    }
  }
  if (now - probePrinted >= 250) {
    probePrinted = now;
    Serial.print(F("FLS_DBG v=1 probe=${DIGITAL_PROBE_KIND}"));
    for (uint8_t i = 0; i < PROBE_COUNT; i++) {
      Serial.print(F(" level_")); Serial.print(PROBE_PINS[i]); Serial.print('='); Serial.print(probeLevel[i]);
      Serial.print(F(" edges_")); Serial.print(PROBE_PINS[i]); Serial.print('='); Serial.print(probeEdges[i]);
      Serial.print(F(" bounces_")); Serial.print(PROBE_PINS[i]); Serial.print('='); Serial.print(probeBounces[i]);
    }
    Serial.println();
  }
}
`
}
