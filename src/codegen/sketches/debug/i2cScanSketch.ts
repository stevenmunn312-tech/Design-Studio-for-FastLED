/**
 * Debug probe: an I2C bus scan. Reads SDA and SCL as plain inputs before the
 * bus starts (an idle bus is held high by its pull-ups), then starts the bus
 * the way the project does (`wireBeginCpp`) and asks every address from 0x08
 * to 0x77 once a second, printing the ones that answer:
 *
 *   FLS_DBG v=1 probe=i2c sdaIdle=1 sclIdle=1 found="3C,68" count=2
 */

export const I2C_SCAN_PROBE_KIND = 'i2c'

export interface I2cScanTarget {
  /** The bus start line for this board, from `wireBeginCpp`. */
  wireBegin: string
  /** The pins to read idle levels from: numbers on ESP boards, else the core's SDA/SCL. */
  sda: number | 'SDA'
  scl: number | 'SCL'
}

const pinExpr = (pin: number | string) => (typeof pin === 'number' ? String(Math.max(0, Math.min(255, Math.trunc(pin)))) : pin)

export function generateI2cScanSketch(target: I2cScanTarget): string {
  return `// Debug: I2C scan — generated by Design Studio for FastLED.
//
// A temporary measuring sketch, not your project. It lists every address that
// answers on the bus, once a second at 115200. Upload the project again when
// you are done.
#include <Wire.h>

static uint8_t sdaIdle = 0, sclIdle = 0;
static uint32_t probePrinted = 0;

void setup() {
  Serial.begin(115200);
  delay(200);
  pinMode(${pinExpr(target.sda)}, INPUT);
  pinMode(${pinExpr(target.scl)}, INPUT);
  delay(5);
  sdaIdle = digitalRead(${pinExpr(target.sda)});
  sclIdle = digitalRead(${pinExpr(target.scl)});
${target.wireBegin}
  Serial.println(F("FLS_DBG v=1 probe=${I2C_SCAN_PROBE_KIND} state=ready"));
}

void loop() {
  if (millis() - probePrinted < 1000) return;
  probePrinted = millis();
  uint8_t count = 0;
  Serial.print(F("FLS_DBG v=1 probe=${I2C_SCAN_PROBE_KIND} sdaIdle="));
  Serial.print(sdaIdle);
  Serial.print(F(" sclIdle="));
  Serial.print(sclIdle);
  Serial.print(F(" found=\\""));
  for (uint8_t address = 0x08; address <= 0x77; address++) {
    Wire.beginTransmission(address);
    if (Wire.endTransmission() == 0) {
      if (count > 0) Serial.print(',');
      if (address < 0x10) Serial.print('0');
      Serial.print(address, HEX);
      count++;
    }
  }
  Serial.print(F("\\" count="));
  Serial.println(count);
}
`
}
