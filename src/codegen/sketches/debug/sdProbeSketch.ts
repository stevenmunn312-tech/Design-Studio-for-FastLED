/**
 * Debug probe: the project's SD card wiring. Starts SPI on the card's pins and
 * mounts it the way the SD player does (`SD.begin(cs, SPI, hz)`, 20 MHz then
 * 4 MHz), then reports whether it mounted, at what speed, the card type and
 * size and how many entries the root holds. Retries every three seconds so a
 * card can be inserted late. ESP32 only, like the SD player.
 *
 *   FLS_DBG v=1 probe=sd mounted=1 mhz=20 type="SDHC" sizeMb=15193 files=12
 */

export const SD_PROBE_KIND = 'sd'

export interface SdProbeTarget {
  csPin: number
  sckPin: number
  misoPin: number
  mosiPin: number
}

const pinOf = (value: number) => Math.max(0, Math.min(255, Math.trunc(value)))

export function generateSdProbeSketch(target: SdProbeTarget): string {
  const cs = pinOf(target.csPin), sck = pinOf(target.sckPin), miso = pinOf(target.misoPin), mosi = pinOf(target.mosiPin)
  return `// Debug: SD card probe — generated by Design Studio for FastLED.
//
// A temporary measuring sketch, not your project. It mounts the card on CS ${cs},
// SCK ${sck}, MISO ${miso}, MOSI ${mosi} and reports at 115200 every three
// seconds. It writes nothing to the card. Upload the project again when you are done.
#include <SPI.h>
#include <SD.h>

static const uint8_t SD_CS = ${cs}, SD_SCK = ${sck}, SD_MISO = ${miso}, SD_MOSI = ${mosi};

static const char* cardTypeName(uint8_t type) {
  switch (type) {
    case CARD_MMC:  return "MMC";
    case CARD_SD:   return "SDSC";
    case CARD_SDHC: return "SDHC";
    default:        return "none";
  }
}

void setup() {
  Serial.begin(115200);
  delay(200);
  pinMode(SD_CS, OUTPUT);
  digitalWrite(SD_CS, HIGH);
  SPI.begin(SD_SCK, SD_MISO, SD_MOSI, SD_CS);
  Serial.println(F("FLS_DBG v=1 probe=${SD_PROBE_KIND} state=ready"));
}

void loop() {
  uint8_t mhz = 20;
  bool mounted = SD.begin(SD_CS, SPI, 20000000);
  if (!mounted) {
    SD.end();
    mhz = 4;
    mounted = SD.begin(SD_CS, SPI, 4000000);
  }
  const uint8_t type = mounted ? SD.cardType() : CARD_NONE;
  unsigned long files = 0;
  if (mounted && type != CARD_NONE) {
    File root = SD.open("/");
    if (root) {
      for (File entry = root.openNextFile(); entry; entry = root.openNextFile()) files++;
      root.close();
    }
  }
  Serial.print(F("FLS_DBG v=1 probe=${SD_PROBE_KIND} mounted="));
  Serial.print(mounted && type != CARD_NONE ? 1 : 0);
  Serial.print(F(" mhz="));
  Serial.print(mounted ? mhz : 0);
  Serial.print(F(" type=\\""));
  Serial.print(cardTypeName(type));
  Serial.print(F("\\" sizeMb="));
  Serial.print(mounted ? (unsigned long)(SD.cardSize() / (1024ULL * 1024ULL)) : 0UL);
  Serial.print(F(" files="));
  Serial.println(files);
  SD.end();
  delay(3000);
}
`
}
