/**
 * Debug probe: one analog pin, read as the project reads it.
 *
 * A temporary measuring sketch, like IR learn: uploaded with `cache: false`,
 * it reads only this pin and prints a versioned `FLS_DBG` line four times a
 * second with the latest, lowest and highest raw reading and the average
 * jump between reads (noise). It uses the project's own full-scale define
 * (`ANALOG_FULL_SCALE_CPP`), so a reading here is a reading there.
 */

import { ANALOG_FULL_SCALE, ANALOG_FULL_SCALE_CPP } from '../../helpers/analogReadCpp'

export const ANALOG_PROBE_KIND = 'analog'

export function generateAnalogProbeSketch(pin: number): string {
  const safe = Math.max(0, Math.min(255, Math.trunc(pin)))
  return `// Debug: analog probe — generated by Design Studio for FastLED.
//
// A temporary measuring sketch, not your project. It reads pin ${safe} and
// prints a line at 115200 four times a second. Upload the project again when
// you are done.
${ANALOG_FULL_SCALE_CPP.join('\n')}

static const uint8_t PROBE_PIN = ${safe};
static int probeLow = 32767, probeHigh = -1, probeLast = -1;
static long probeSum = 0, probeJitter = 0;
static int probeCount = 0;
static uint32_t probePrinted = 0;

void setup() {
  Serial.begin(115200);
  delay(200);
  Serial.println(F("FLS_DBG v=1 probe=${ANALOG_PROBE_KIND} state=ready"));
}

void loop() {
  const int raw = analogRead(PROBE_PIN);
  if (raw < probeLow) probeLow = raw;
  if (raw > probeHigh) probeHigh = raw;
  if (probeLast >= 0) probeJitter += abs(raw - probeLast);
  probeLast = raw;
  probeSum += raw;
  probeCount++;
  if (millis() - probePrinted >= 250 && probeCount > 1) {
    probePrinted = millis();
    Serial.print(F("FLS_DBG v=1 probe=${ANALOG_PROBE_KIND} raw="));
    Serial.print(probeSum / probeCount);
    Serial.print(F(" min="));
    Serial.print(probeLow);
    Serial.print(F(" max="));
    Serial.print(probeHigh);
    Serial.print(F(" noise="));
    Serial.print(probeJitter / (probeCount - 1));
    Serial.print(F(" adcMax="));
    Serial.println((long)${ANALOG_FULL_SCALE});
    probeSum = 0;
    probeJitter = 0;
    probeCount = 0;
    probeLast = -1;
  }
  delay(2);
}
`
}
